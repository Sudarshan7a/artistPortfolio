/*
General Commission Guidelines
Work Pace: 
            I work at my own pace to ensure quality, so please avoid rushing the process.
Provide Clear References:
            When requesting a commission, please provide clear details and reference images if possible. Visual 
            references  help me complete your commission faster and more accurately.    
Original Character Design:
            If your Original Character (OC) doesn’t have an existing visual design or draft, there will be an 
            additional fee of $50–$200 for character visualization.
Canvas Size Options:
           You can select any canvas size up to 8K resolution (7680x4320). Please specify the scale or aspect ratio 
             you’d like for the commission.
Right to Decline:
           I reserve the right to decline any commission request if it makes me uncomfortable.

Payment, Cancellation & Refund Policy
Payment 
    A 50% deposit (Payment #1) is required upfront to secure your spot in the commission queue. The remaining 50% (Payment #2) is due once you approve the colored sketch.
    If preferred, you may also pay the full amount (100%) at the start of your request.
Accepted Payment Methods
    Payments can be made via VGen (coming soon) or PayPal.
    For clients in Vietnam: Bank transfer is recommended for smoother transactions.
Cancellation & Refund Policy
    If you cancel during the Color Sketch Phase: A 50% refund of your deposit (Payment #1) or 75% of the total payment will be issued.
    If you cancel during the Coloring/Rendering Phase: A 10% refund of the total payment will be issued.
    If I (the artist) cancel the commission: You will receive a full refund (100%) of any payments made.
    No refunds are available once the commission is completed.

Copyright & Usage Policy
Portfolio Use:
            I may showcase finished artworks (with a watermark) in this website’s Gallery or on social media. Clients retain 
            copyright of their Original Characters and will be credited as their owner.
Personal Usage Rights:
           Clients are welcome to use the commissioned artwork for personal enjoyment (e.g., as wallpaper, desktop 
            background, or print for home display), provided they adhere to the terms above.
Prohibited Uses:
            My artwork may not be used for AI training or sold as NFTs.
            You may not claim, edit, trace, copy, or modify any of my finished art without permission.
Commercial Use Fees:
           Commissions intended for commercial use will incur an additional fee of 100% of the original price.
Streaming Policy:
           I occasionally stream my work in select artist communities on Discord. If you prefer your commission to remain 
            private until completion, an additional 20% fee will apply.

Commission Process
Review Terms - Ensure you’ve read and agree to the terms and conditions above.
Initiate Contact - Reach out through one of the options in the Contact section. I’ll respond within 24 hours to discuss your request in more detail. Once we confirm the specifics, I’ll decide whether to accept the commission.
Sketch & Initial Payment - After confirmation and receiving Payment #1 or the full amount, I’ll begin with a line sketch, progressing to a color sketch. You have 3 free revisions during the sketch phase. Additional major revisions beyond these will cost $10 each.
Approval & Final Payment - Once you approve the color sketch and submit Payment #2, I’ll proceed to the color and rendering phase. During this phase, you’re entitled to:
                                1 major revision (e.g., changes to poses, composition, major details)
                                3 minor revisions (e.g., facial expressions, minor details, small props)
                            After this, additional revisions cost $5 for minor adjustments and $20 for major ones.
Final Delivery - When the artwork is complete, I’ll send it to you via Email or Discord (full-resolution files, plus additional versions for higher-tier commissions). 
*/

